import { GEAR_SLOTS, SLOT_KINDS, type GearPiece, type GearSlot, type PieceKind } from '../charter/look.js'
import { BUILT_IN_PIECES } from './pieces.gen.js'

/** A built-in piece as tools/blender/pieces.py lists it: modelled by us, free for everyone. */
export interface BuiltInPiece {
  id: string
  name: string
  kind: PieceKind
  /** Words a prompt may use for it, longest first where it matters ("top hat" before "hat"). */
  tags: readonly string[]
  /** Its 'primary' material's own colour, when it has one a player can change. */
  tint: string | null
  tris: number
}

/** A piece in the asset repository, built-in or generated by a player, as pickers and the prompt see it. */
export interface PieceEntry {
  id: string
  name: string
  kind: PieceKind
  tags: readonly string[]
  url: string
  thumb: string
  tint: string | null
  source: 'built-in' | 'community'
  /** How many saved heroes wear it (community pieces). */
  uses?: number
}

export const builtInUrl = (id: string) => `/kit/pieces/${id}.glb`

export const BUILT_IN: readonly PieceEntry[] = BUILT_IN_PIECES.map((p) => ({ ...p, url: builtInUrl(p.id), thumb: `/kit/pieces/${p.id}.webp`, source: 'built-in' as const }))

const byId = new Map(BUILT_IN.map((p) => [p.id, p]))

export function builtIn(id: string): PieceEntry | undefined {
  return byId.get(id)
}

/** True when a piece of this kind can hang in this slot. */
export function fits(kind: PieceKind, slot: GearSlot): boolean {
  return SLOT_KINDS[slot].includes(kind)
}

/** Where a piece goes when nothing says otherwise: a hand piece in the right hand, an off-hand piece in the left. */
export function slotFor(kind: PieceKind): GearSlot {
  return GEAR_SLOTS.find((slot) => SLOT_KINDS[slot][0] === kind) ?? 'hand_l'
}

/** The look's record of a worn piece. */
export function wearing(entry: Pick<PieceEntry, 'id' | 'url'>, color?: string): GearPiece {
  return { id: entry.id, url: entry.url, ...(color ? { color } : {}) }
}
